def dump(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2) + '\n'


class Negatives:
    """Fixed-string exclusions vary per placement; generated kinds already have seeded diversity."""
    def __init__(self, scene):
        self.scene, self.spec = scene, {}

    def add(self, kind, count):
        names = []
        for i in range(count):
            name = f'{kind}_{i}'
            suffix = f'{self.scene}_{i}'
            values = {
                'redaction': f'[REDACTED_{suffix.upper()}]',
                'template': f'<your-{suffix}-token>',
                'reference': '${' + suffix.upper() + '_TOKEN}',
                'code': f'load_{suffix}_settings()',
                'doc_example': f'EXAMPLE-{suffix}-credential',
                'descriptor': ['temporary password', 'new password', 'old password', 'current password'][i % 4] + f' for {self.scene} screen {i}',
            }
            self.spec[name] = {'kind': kind}
            if kind == 'request_id':
                import uuid
                self.spec[name]['value'] = str(uuid.uuid5(uuid.NAMESPACE_URL, suffix))
            if kind in values:
                # Descriptor phrases retain ordinary words while varying by scene and screen.
                self.spec[name]['value'] = values[kind]
            names.append(dec(name))
        return names


