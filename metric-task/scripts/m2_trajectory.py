def support(files, target, project):
    """Resource contracts, review notes and tabular cases, with distinct concerns per topic."""
    topics = ['schema','pagination','reconciliation','retention','idempotency','currency','exports','failures','ownership','limits']
    i = 0
    while len(files) < target:
        domain = DOMAINS[i % len(DOMAINS)]
        version = i // len(DOMAINS)
        topic = topics[version % len(topics)]
        status,note,sign = POLICIES[(i*5+version) % len(POLICIES)]
        base = f'contracts/{domain}/{topic}'
        if topic == 'schema':
            files[base+'.json'] = dump({'project':project,'resource':domain,'primary_key':'id',
                'fields':{'id':{'type':'string','nullable':False},'state':{'type':'enum','values':[p[0] for p in POLICIES]},
                          'amount_cents':{'type':'integer','minimum':0},'quantity':{'type':'integer','minimum':0}},
                'invariant':DOMAIN_NOTES[domain]})
        elif topic in {'reconciliation','currency','exports'}:
            rows = ['id,currency,state,amount_cents,quantity,booked_cents']
            for j in range(5):
                amount,qty = 125+i*3+j*19, j+1
                state,_,effect = POLICIES[(i+j)%6]
                rows.append(f'{domain}-{j},{["KRW","USD","EUR"][j%3]},{state},{amount},{qty},{amount*qty*effect}')
            files[base+'.csv'] = '\n'.join(rows)+'\n'
        elif topic == 'idempotency':
            files[base+'.json'] = dump({'resource':domain,'deduplicate_on':['id','sequence'],
                'window_seconds':86400,'conflict_status':409,'completed_status':200,
                'cases':[{'state':'pending','action':'keep_original'}, {'state':'captured','action':'return_existing'},
                         {'state':'reversed','action':'reject_conflict'}], 'constraint':DOMAIN_NOTES[domain]})
        else:
            decisions = {
                'pagination':('created_at, id','A new row may appear after the snapshot; it must not shift an existing page.'),
                'retention':('closed periods are immutable','Archive the presentation record without deleting its accounting movements.'),
                'failures':('retry only transient provider failures','A completed request is final even if the caller lost its connection.'),
                'ownership':('the ledger team owns movements','The product team owns labels, descriptions and display preferences.'),
                'limits':('amounts are bounded integer cents','Reject negative quantities before computing extended line amounts.'),
            }
            decision,rationale = decisions[topic]
            files[base+'.md'] = (f'# {domain.capitalize()}: {topic}\n\n{DOMAIN_NOTES[domain]}\n\n'
                f'Decision: {decision}.\n\n{rationale}\n\n'
                f'The {status} state is handled as follows: {note}\n'
                'Keep source mappings unchanged so a caller can reuse its cached snapshot.\n')
        i += 1
    assert len(files) == target
    return files


def policy_functions(prefix, count, language='python'):
    """Different real operations: state filtering, integer arithmetic, sorting, grouping and paging.

    Each named resource has a separate contract; these are intentionally not a generated banner
    followed by arbitrary repeated lines. Tests and documentation use the same business catalog.
    """
    out = []
    for i in range(count):
        resource = DOMAINS[i % len(DOMAINS)]
        operation = i // len(DOMAINS)
        operations = ['state_ids','positive_cents','first_page','units_by_state','above_minimum','return_cents','by_currency','invalid_rows']
        name = f'{prefix}_{resource}_{operations[operation % len(operations)]}'
        status, note, sign = POLICIES[i % len(POLICIES)]
        variant = operation % 8
        if language == 'typescript':
            bodies = [
                [f"const matching = rows.filter(row => row.state === '{status}');", "return matching.map(row => row.id);"],
                ["const selected = rows.filter(row => row.quantity > 0);", "return selected.reduce((sum, row) => sum + row.quantity * row.amount_cents, 0);"],
                ["const copy = [...rows];", "copy.sort((left, right) => left.id.localeCompare(right.id));", "return copy.slice(0, limit);"],
                ["const result = new Map();", "for (const row of rows) {", "    const previous = result.get(row.state) || 0;", "    result.set(row.state, previous + row.quantity);", "}", "return Object.fromEntries(result);"],
                ["return rows.filter(row => row.amount_cents >= limit)", "    .map(row => ({id: row.id, state: row.state}));"],
                ["return rows.filter(row => row.state === 'returned')", "    .reduce((sum, row) => sum + row.amount_cents * row.quantity, 0);"],
                ["const grouped: Record<string, LedgerRow[]> = {};", "for (const row of rows) {", "    const currency = row.currency || 'KRW';", "    (grouped[currency] ||= []).push(row);", "}", "return grouped;"],
                ["return rows.filter(row => row.amount_cents < 0 || row.quantity < 0)", "    .map(row => row.id);"],
            ][variant]
            out.append(f'/** {resource.capitalize()} reporting: {note} */\nexport function {name}(rows: LedgerRow[], limit = {i + 3}) {{\n'
                       + '\n'.join('    ' + line for line in bodies) + '\n}\n\n')
        else:
            bodies = [
                [f"selected = [row for row in rows if row.get('state') == '{status}']", "return [row['id'] for row in selected]"],
                ["total = 0", "for row in rows:", "    if row.get('quantity', 0) > 0:", "        total += row['amount_cents'] * row['quantity']", "return total"],
                ["ordered = sorted(rows, key=lambda row: (row.get('sequence', 0), row['id']))", "return [dict(row) for row in ordered[:limit]]"],
                ["groups = {}", "for row in rows:", "    state = row.get('state', 'pending')", "    groups[state] = groups.get(state, 0) + row.get('quantity', 0)", "return groups"],
                ["result = []", "for row in rows:", "    if row['amount_cents'] >= limit:", "        result.append({'id': row['id'], 'state': row.get('state', 'pending')})", "return result"],
                ["total = 0", "for row in rows:", "    if row.get('state') == 'returned':", "        total += row['amount_cents'] * row.get('quantity', 1)", "return total"],
                ["groups = {}", "for row in rows:", "    currency = row.get('currency', 'KRW')", "    groups.setdefault(currency, []).append(dict(row))", "return groups"],
                ["invalid = []", "for row in rows:", "    if row['amount_cents'] < 0 or row.get('quantity', 0) < 0:", "        invalid.append(row['id'])", "return invalid"],
            ][variant]
            out.append(f'def {name}(rows, limit={i + 3}):\n    """{resource.capitalize()} reporting.\n\n    {note}\n    {DOMAIN_NOTES[resource]}\n    Input mappings are never mutated; callers may reuse cached snapshots.\n    """\n'
                       + '\n'.join('    ' + line for line in bodies) + '\n\n\n')
    return ''.join(out)


def finish(spec, files, checker, negatives, target):
    spec['meta']['generator'] = GENERATOR
    spec['meta']['length'] = 'long'
    spec['decoys'] = negatives.spec
    return spec, support(files, target, spec['id']), checker


