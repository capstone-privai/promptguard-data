"""Build wordlists/agent_traffic_common.txt, the background-corpus part of label_rules.is_common.

Run from the repository root, after converting both corpora (convert_swe_gym.py, convert_openhands_feedback.py):
  python metric-detection/scripts/build_common_tokens.py

A token is common when it occurs at least MIN_COUNT times in at least MIN_SESSIONS sessions of SWE-Gym and
openhands-feedback, real agent traffic with almost no credentials. Gold values of the two datasets are left out.
English words (SCOWL) and digit-only tokens are already common and are not written.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import re

from label_rules import WORDLISTS, _wordlist

SOURCES = ("SWE-Gym", "openhands-feedback")
MIN_COUNT, MIN_SESSIONS = 5, 3
TOKEN = re.compile(r"[^\s'\"`()\[\]{}<>,;|&=:/\\]+")


def build(root: Path) -> tuple[list[str], list[str]]:
    count, sessions, gold, versions = Counter(), defaultdict(set), set(), []
    for name in SOURCES:
        texts = {}
        with (root / "data_test" / f"sessions_from_{name}.jsonl").open(encoding="utf-8") as f:
            for line in f:
                s = json.loads(line)
                versions.append(s["meta"]["dataset_version"])
                for item in s["items"]:
                    texts[(s["session_id"], item["item_id"])] = item["text"]
                    for token in TOKEN.findall(item["text"]):
                        token = token.strip(".!?*").lower()
                        if token:
                            count[token] += 1
                            sessions[token].add(s["session_id"])
        with (root / "data_answer" / f"gold_from_{name}.jsonl").open(encoding="utf-8") as f:
            for line in f:
                g = json.loads(line)
                gold.add(texts[(g["session_id"], g["item_id"])][g["span"]["start"]:g["span"]["end"]].lower())
    words = _wordlist("scowl-en_US-60.txt")
    tokens = sorted(t for t, n in count.items()
                    if n >= MIN_COUNT and len(sessions[t]) >= MIN_SESSIONS
                    and t not in words and not t.isdigit() and t not in gold)
    return tokens, sorted(set(versions))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1],
                        help="metric-detection folder holding data_test/ and data_answer/")
    args = parser.parse_args()
    tokens, versions = build(args.root)
    header = [f"# Generated by build_common_tokens.py from {', '.join(versions)}",
              f"# tokens in >= {MIN_SESSIONS} sessions and >= {MIN_COUNT} times, minus SCOWL words, digits and gold values"]
    (WORDLISTS / "agent_traffic_common.txt").write_text("\n".join(header + tokens) + "\n", encoding="utf-8")
    print(f"{len(tokens)} tokens")


if __name__ == "__main__":
    main()
